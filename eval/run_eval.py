"""
Offline evaluation for the support agent.

Runs every case in eval/golden.jsonl through the demo-mode agent and reports:

  * retrieval hit@1, hit@3 and MRR against the expected runbook
  * status accuracy (answered, refused, or "no match" when it should be)
  * tenant leaks: any other tenant's id or request id showing up in an answer
    or in the log rows returned to the caller (this must be zero)
  * a comparison of the three chunking strategies on the same cases

Usage:
    python -m eval.run_eval              # prints a report, exits 1 if a gate fails
    python -m eval.run_eval --write      # also rewrites eval/RESULTS.md
"""

import argparse
import json
import sys
from pathlib import Path
from statistics import mean

from agent.local_agent import LocalSupportAgent
from offline.store import LocalStore
from retrieval.local_retriever import CHUNKING_STRATEGIES, DEFAULT_STRATEGY, LocalRunbookRetriever

ROOT = Path(__file__).resolve().parent
GOLDEN = ROOT / "golden.jsonl"
RESULTS = ROOT / "RESULTS.md"

# Gates the CI build enforces. Leaks are a hard zero.
MIN_HIT_AT_3 = 0.90
MIN_STATUS_ACCURACY = 0.90


def load_cases():
    return [json.loads(line) for line in GOLDEN.read_text().splitlines() if line.strip()]


def tenant_markers(store: LocalStore):
    """Map each tenant to strings that would prove its data leaked."""
    markers = {}
    for tenant in store.known_tenants():
        rows = store.query_logs(tenant, hours_back=24 * 365, limit=10_000)["results"]
        markers[tenant] = {tenant} | {row["request_id"] for row in rows}
    return markers


def run(strategy: str, cases, store: LocalStore, markers):
    agent = LocalSupportAgent(store=store, retriever=LocalRunbookRetriever(strategy=strategy))
    rows = []
    for case in cases:
        out = agent.invoke(case["question"], tenant_id=case["tenant_id"])
        sources = out["sources"]
        expected = case["expected_runbook"]
        rank = sources.index(expected) + 1 if expected in sources else None

        visible = out["text"] + " " + json.dumps(out["log_rows"])
        leaked = sorted(
            marker for tenant, values in markers.items() if tenant != case["tenant_id"]
            for marker in values if marker in visible
        )
        rows.append({
            "id": case["id"], "type": case["type"], "expected": expected, "sources": sources,
            "rank": rank, "status": out["status"], "status_ok": out["status"] == case["expected_status"],
            "leaks": leaked, "latency_ms": out["latency_ms"],
            "context_words": sum(len(h.split()) for h in _context_texts(agent, out)),
        })
    return rows


def _context_texts(agent, out):
    # Words of retrieved context the answer step would see (a proxy for prompt tokens).
    texts = []
    for rb_id in out["sources"]:
        chunk = next((c for c in agent.retriever.chunks if c.runbook_id == rb_id), None)
        if chunk:
            texts.append(chunk.text)
    return texts


def summarize(rows):
    retrieval = [r for r in rows if r["expected"]]
    return {
        "cases": len(rows),
        "hit@1": mean(1.0 if r["rank"] == 1 else 0.0 for r in retrieval),
        "hit@3": mean(1.0 if r["rank"] else 0.0 for r in retrieval),
        "mrr": mean(1.0 / r["rank"] if r["rank"] else 0.0 for r in retrieval),
        "status_accuracy": mean(1.0 if r["status_ok"] else 0.0 for r in rows),
        "leaks": sum(len(r["leaks"]) for r in rows),
        "avg_context_words": mean(r["context_words"] for r in rows if r["sources"]),
        "p50_latency_ms": sorted(r["latency_ms"] for r in rows)[len(rows) // 2],
    }


def by_type(rows):
    groups = {}
    for r in rows:
        groups.setdefault(r["type"], []).append(r)
    out = {}
    for name, items in groups.items():
        scored = [r for r in items if r["expected"]]
        out[name] = {
            "n": len(items),
            "hit@1": mean(1.0 if r["rank"] == 1 else 0.0 for r in scored) if scored else None,
            "status_ok": mean(1.0 if r["status_ok"] else 0.0 for r in items),
        }
    return out


def pct(value):
    return "n/a" if value is None else f"{value * 100:.0f}%"


def render(main, main_rows, sweep):
    lines = ["# Eval results", "",
             f"Generated by `python -m eval.run_eval --write` on {main['cases']} golden cases "
             f"(`eval/golden.jsonl`). Default chunking: `{DEFAULT_STRATEGY}`.", "",
             "| Metric | Value |", "|---|---|",
             f"| Retrieval hit@1 | {pct(main['hit@1'])} |",
             f"| Retrieval hit@3 | {pct(main['hit@3'])} |",
             f"| MRR | {main['mrr']:.2f} |",
             f"| Status accuracy (answer / refuse / no match) | {pct(main['status_accuracy'])} |",
             f"| Cross-tenant leaks | {main['leaks']} |",
             f"| Median latency (offline, no LLM) | {main['p50_latency_ms']} ms |", "",
             "## By case type", "", "| Type | Cases | hit@1 | Status correct |", "|---|---|---|---|"]
    for name, stats in by_type(main_rows).items():
        lines.append(f"| {name} | {stats['n']} | {pct(stats['hit@1'])} | {pct(stats['status_ok'])} |")
    lines += ["", "## Chunking comparison", "",
              "| Strategy | hit@1 | hit@3 | MRR | Avg context words |", "|---|---|---|---|---|"]
    for name, s in sweep.items():
        lines.append(f"| `{name}` | {pct(s['hit@1'])} | {pct(s['hit@3'])} | {s['mrr']:.2f} | {s['avg_context_words']:.0f} |")
    misses = [r for r in main_rows if (r["expected"] and r["rank"] != 1) or not r["status_ok"]]
    lines += ["", "## Misses", ""]
    if not misses:
        lines.append("None.")
    for r in misses:
        lines.append(f"- `{r['id']}` ({r['type']}): expected `{r['expected']}`, got {r['sources'] or 'nothing'}, "
                     f"status `{r['status']}`")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="rewrite eval/RESULTS.md")
    args = parser.parse_args(argv)

    cases = load_cases()
    store = LocalStore()
    markers = tenant_markers(store)

    sweep = {}
    main_rows = None
    for strategy in CHUNKING_STRATEGIES:
        rows = run(strategy, cases, store, markers)
        sweep[strategy] = summarize(rows)
        if strategy == DEFAULT_STRATEGY:
            main_rows = rows
    main_summary = sweep[DEFAULT_STRATEGY]

    report = render(main_summary, main_rows, sweep)
    print(report)
    if args.write:
        RESULTS.write_text(report)

    failures = []
    if main_summary["leaks"]:
        failures.append(f"{main_summary['leaks']} cross-tenant leaks")
    if main_summary["hit@3"] < MIN_HIT_AT_3:
        failures.append(f"hit@3 {main_summary['hit@3']:.2f} < {MIN_HIT_AT_3}")
    if main_summary["status_accuracy"] < MIN_STATUS_ACCURACY:
        failures.append(f"status accuracy {main_summary['status_accuracy']:.2f} < {MIN_STATUS_ACCURACY}")
    if failures:
        print("EVAL GATE FAILED: " + "; ".join(failures))
        return 1
    print("Eval gates passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
